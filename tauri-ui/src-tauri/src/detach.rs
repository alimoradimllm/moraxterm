//! Pure helpers for detached terminal windows (the window label that carries the terminal id), kept apart from the Tauri code so they can be unit tested.

use serde::{Deserialize, Serialize};

pub const WINDOW_PREFIX: &str = "term-";

/// File (in the app data folder) that remembers where the last separate terminal window was.
pub const GEOMETRY_FILE: &str = "detached-window.json";

/// A window's place on screen in physical pixels: `x`/`y` are the outer top-left corner, `width`/`height` the inner (client) size,
/// which is what `set_size` takes.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Geometry {
    pub x: i32,
    pub y: i32,
    pub width: u32,
    pub height: u32,
}

/// A monitor's rectangle in the same coordinates.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Area {
    pub x: i32,
    pub y: i32,
    pub width: u32,
    pub height: u32,
}

const MIN_WIDTH: u32 = 300;
const MIN_HEIGHT: u32 = 200;
const MAX_SIDE: u32 = 20_000;
/// How much of the window must lie on one monitor for the user to be able to reach and drag it.
const MIN_VISIBLE_WIDTH: i64 = 120;
const MIN_VISIBLE_HEIGHT: i64 = 60;

/// True when a remembered geometry is safe to reuse: a sane size, and enough of the window on a monitor that is connected now (a saved
/// position on an unplugged monitor, or the -32000 Windows reports for a minimised window, must never put the window out of reach).
pub fn usable(geometry: &Geometry, monitors: &[Area]) -> bool {
    if geometry.width < MIN_WIDTH
        || geometry.height < MIN_HEIGHT
        || geometry.width > MAX_SIDE
        || geometry.height > MAX_SIDE
    {
        return false;
    }
    let left = i64::from(geometry.x);
    let top = i64::from(geometry.y);
    let right = left + i64::from(geometry.width);
    let bottom = top + i64::from(geometry.height);
    monitors.iter().any(|m| {
        let m_left = i64::from(m.x);
        let m_top = i64::from(m.y);
        let overlap_w = right.min(m_left + i64::from(m.width)) - left.max(m_left);
        let overlap_h = bottom.min(m_top + i64::from(m.height)) - top.max(m_top);
        overlap_w >= MIN_VISIBLE_WIDTH && overlap_h >= MIN_VISIBLE_HEIGHT
    })
}

pub fn parse_geometry(text: &str) -> Option<Geometry> {
    serde_json::from_str(text).ok()
}

pub fn geometry_json(geometry: &Geometry) -> String {
    serde_json::to_string(geometry).unwrap_or_default()
}

/// A terminal id is generated by the app (`tab-<millis>-<n>`), but it crosses the IPC boundary, so only plain identifier characters are
/// accepted: they are safe inside a window label (letters, digits, `-`, `_`) and inside a URL.
pub fn valid_terminal_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 80
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

pub fn window_label(id: &str) -> Option<String> {
    valid_terminal_id(id).then(|| format!("{WINDOW_PREFIX}{id}"))
}

/// The terminal id a window label belongs to, or None for any other window (the main window).
pub fn terminal_id_of_label(label: &str) -> Option<&str> {
    label
        .strip_prefix(WINDOW_PREFIX)
        .filter(|id| valid_terminal_id(id))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_plain_identifiers_are_accepted_as_terminal_ids() {
        for ok in ["tab-1760000000000-0", "abc_DEF-9", "x"] {
            assert!(valid_terminal_id(ok), "{ok}");
        }
        for bad in [
            "",
            "a b",
            "a/b",
            "a\\b",
            "..",
            "a?b=c",
            "a&b",
            "a#b",
            "日本",
            "a\nb",
            "term-x y",
            &"x".repeat(81),
        ] {
            assert!(!valid_terminal_id(bad), "{bad:?}");
        }
    }

    const SCREEN: Area = Area {
        x: 0,
        y: 0,
        width: 1920,
        height: 1080,
    };

    fn at(x: i32, y: i32, width: u32, height: u32) -> Geometry {
        Geometry {
            x,
            y,
            width,
            height,
        }
    }

    #[test]
    fn a_window_on_a_connected_monitor_is_reused() {
        assert!(usable(&at(100, 80, 900, 600), &[SCREEN]));
        // partly off the edge is fine while enough of it can still be grabbed
        assert!(usable(&at(1800, 900, 900, 600), &[SCREEN]));
        assert!(usable(&at(-700, 100, 900, 600), &[SCREEN]));
    }

    #[test]
    fn a_window_that_cannot_be_reached_is_not_reused() {
        // a monitor that is no longer connected, and Windows' position for a minimised window
        assert!(!usable(&at(3000, 100, 900, 600), &[SCREEN]));
        assert!(!usable(&at(-32000, -32000, 900, 600), &[SCREEN]));
        // only a sliver visible
        assert!(!usable(&at(1900, 100, 900, 600), &[SCREEN]));
        assert!(!usable(&at(100, 1070, 900, 600), &[SCREEN]));
        // no monitors known
        assert!(!usable(&at(100, 80, 900, 600), &[]));
    }

    #[test]
    fn a_second_monitor_counts_and_absurd_sizes_do_not() {
        let right = Area {
            x: 1920,
            y: 0,
            width: 1280,
            height: 1024,
        };
        assert!(usable(&at(2000, 50, 900, 600), &[SCREEN, right]));
        assert!(!usable(&at(2000, 50, 900, 600), &[SCREEN]));
        assert!(!usable(&at(100, 80, 10, 10), &[SCREEN]));
        assert!(!usable(&at(100, 80, 100_000, 600), &[SCREEN]));
    }

    #[test]
    fn geometry_survives_a_round_trip_and_bad_files_are_ignored() {
        let g = at(-5, 40, 1000, 700);
        assert_eq!(parse_geometry(&geometry_json(&g)), Some(g));
        assert_eq!(parse_geometry(""), None);
        assert_eq!(parse_geometry("not json"), None);
        assert_eq!(parse_geometry("{\"x\":1}"), None);
        assert_eq!(
            parse_geometry("{\"x\":1,\"y\":2,\"width\":-3,\"height\":4}"),
            None
        );
    }

    #[test]
    fn labels_round_trip_and_never_match_the_main_window() {
        assert_eq!(window_label("tab-1-0").as_deref(), Some("term-tab-1-0"));
        assert_eq!(window_label("bad id"), None);
        assert_eq!(terminal_id_of_label("term-tab-1-0"), Some("tab-1-0"));
        assert_eq!(terminal_id_of_label("main"), None);
        assert_eq!(terminal_id_of_label("term-"), None);
        assert_eq!(terminal_id_of_label("term-a b"), None);
        assert_eq!(terminal_id_of_label("terminal-1"), None);
    }
}
