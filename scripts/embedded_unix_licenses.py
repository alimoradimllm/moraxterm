#!/usr/bin/env python3
"""Write docs/EMBEDDED_UNIX_PACKAGES.md from the embedded Unix runtime archive that the Windows installer bundles.

It reads the pacman database inside the archive (var/lib/pacman/local/*/desc), so the package names, versions and SPDX
licence identifiers are what the archive actually contains, not what upstream says today. Each package gets the MSYS2 source
archive URL at the exact version, which is where the corresponding source of the GPL programs can be obtained.

Usage: python scripts/embedded_unix_licenses.py [archive] [--check-urls]
The archive is large and untracked, so CI cannot run this; regenerate it whenever the archive changes.
"""
import hashlib, os, re, sys, tarfile, time, urllib.request, urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ARCHIVE = ROOT / "tauri-ui" / "src-tauri" / "resources" / "Moraxterm_EmbeddedUnix_x64_0.1.24.tar.xz"
OUT = ROOT / "docs" / "EMBEDDED_UNIX_PACKAGES.md"
RUNTIME_DB = "./var/lib/pacman/local/"
LICENSE_DIR = "./usr/share/licenses/"
SOURCE_BASE = "https://repo.msys2.org/msys/sources/"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def parse_desc(text):
    sections, current = {}, None
    for line in text.splitlines():
        m = re.match(r"%(\w+)%$", line)
        if m:
            current = m.group(1)
            sections[current] = []
        elif line and current:
            sections[current].append(line)
    return sections


def read_archive(path):
    packages, license_dirs, exe_count = [], set(), 0
    with tarfile.open(path, mode="r:xz") as tar:
        for member in tar:
            name = member.name
            if name.startswith(RUNTIME_DB) and name.endswith("/desc") and member.isfile():
                sec = parse_desc(tar.extractfile(member).read().decode("utf-8", "replace"))
                one = lambda key: (sec.get(key) or [""])[0]
                packages.append({
                    "name": one("NAME"), "version": one("VERSION"), "base": one("BASE") or one("NAME"),
                    "license": " ; ".join(sec.get("LICENSE") or []) or "(none listed)", "url": one("URL"),
                })
            elif name.startswith(LICENSE_DIR) and member.isdir():
                license_dirs.add(name[len(LICENSE_DIR):].strip("/").split("/")[0])
            elif re.match(r"^\./usr/bin/[^/]+\.exe$", name):
                exe_count += 1
    packages.sort(key=lambda p: p["name"])
    return packages, license_dirs, exe_count


def is_copyleft(license_text):
    return "GPL" in license_text.upper() or "MPL" in license_text.upper()


def url_state(url, attempts=4):
    """'ok' (HTTP 200), 'missing' (HTTP 404/410), or 'unchecked' (network error or throttling after retries).
    Only a real 404 is reported as missing: a throttled or failed request says nothing about whether the file exists."""
    import time, urllib.error
    for attempt in range(attempts):
        try:
            request = urllib.request.Request(url, method="HEAD")
            with urllib.request.urlopen(request, timeout=30) as response:
                if response.status == 200:
                    return "ok"
        except urllib.error.HTTPError as error:
            if error.code in (404, 410):
                return "missing"
        except Exception:
            pass
        time.sleep(2 * (attempt + 1))
    return "unchecked"


def render(archive, packages, license_dirs, exe_count, url_status):
    copyleft = [p for p in packages if is_copyleft(p["license"])]
    shipped = [p for p in copyleft if p["name"] in license_dirs]
    lines = [
        "# Embedded Unix runtime: packages, licences and source",
        "",
        "Generated by `scripts/embedded_unix_licenses.py` from the archive the Windows installer bundles. Do not edit by hand.",
        "",
        f"- Archive: `{archive.name}`",
        f"- SHA-256: `{sha256(archive)}`",
        f"- Packages in its runtime database: {len(packages)} ({len(copyleft)} under a GPL, LGPL or MPL licence)",
        f"- Programs in `usr/bin`: {exe_count} `.exe` files",
        f"- Licence directories the archive ships (`usr/share/licenses/<package>`): {len(license_dirs)}; of the {len(copyleft)} copyleft packages, {len(shipped)} have one",
        "",
        "Moraxterm starts these programs as separate processes and does not link against them. Each keeps its own licence. The full text of the",
        "licences that apply to the copyleft packages is in [`LICENSES/`](../LICENSES/). The source for each package, at the exact version in the",
        "archive, is the MSYS2 source archive linked in the last column.",
        "",
        "Licence identifiers are copied from the package database. Entries without an `spdx:` prefix (for example `GPL`, `GPL3`, `custom`) are older",
        "MSYS2 metadata that does not say which version of the licence applies; check the package's own source before relying on one.",
        "",
        "| Package | Version | Licence (from package database) | Licence dir shipped | Upstream | Source archive |",
        "|---|---|---|---|---|---|",
    ]
    for p in packages:
        source = f"{SOURCE_BASE}{urllib.parse.quote(p['base'] + '-' + p['version'])}.src.tar.zst"
        mark = ""
        if url_status is not None and source in url_status:  # only claim what was actually checked
            mark = {"ok": " (HTTP 200)", "missing": " (**HTTP 404**)", "unchecked": " (not checked)"}[url_status[source]]
        shipped_flag = "yes" if p["name"] in license_dirs else ("no" if is_copyleft(p["license"]) else "-")
        lines.append(f"| {p['name']} | {p['version']} | {p['license']} | {shipped_flag} | {p['url'] or '-'} | [{p['base']}]({source}){mark} |")
    lines += [
        "",
        "`Licence dir shipped`: `yes` means the archive contains `usr/share/licenses/<package>`; `no` marks a copyleft package without one;",
        "`-` is a package with no copyleft licence. The directory name is matched to the package name exactly, so a package whose licence",
        "directory has a different name could show `no` here although some text is present (none did for the 0.1.24 archive).",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    check_urls = "--check-urls" in argv
    args = [a for a in argv if not a.startswith("--")]
    archive = Path(args[0]) if args else DEFAULT_ARCHIVE
    if not archive.is_file():
        print(f"archive not found: {archive}", file=sys.stderr)
        return 2
    packages, license_dirs, exe_count = read_archive(archive)
    if not packages:
        print("no packages found in the runtime database; refusing to write an empty manifest", file=sys.stderr)
        return 1
    url_status = None
    if check_urls:
        url_status = {}
        for p in packages:
            url = f"{SOURCE_BASE}{urllib.parse.quote(p['base'] + '-' + p['version'])}.src.tar.zst"
            if url not in url_status:  # packages built from one source share one archive
                url_status[url] = url_state(url)
                time.sleep(0.4)  # be gentle with a volunteer-run server
        counts = {k: sum(v == k for v in url_status.values()) for k in ("ok", "missing", "unchecked")}
        print(f"distinct source archives: {len(url_status)}  HTTP 200: {counts['ok']}  404: {counts['missing']}  not checked: {counts['unchecked']}")
        for u, v in url_status.items():
            if v != "ok":
                print("  ", v, u)
    OUT.write_text(render(archive, packages, license_dirs, exe_count, url_status), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(packages)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
