#!/usr/bin/env python3
"""Keep README.md and AGENTS.md change indexes in step with docs/changes/.

Every change adds one fragment file `docs/changes/YYYY-MM-DD-<slug>.md`. Fragments never
collide between contributors, so concurrent work does not conflict. The "Recent changes"
block in README.md and the change index in AGENTS.md are generated from them.

    docs_sync.py new <slug>                  create a fragment from the template
    docs_sync.py generate [--verify]         rewrite the generated blocks (--verify: fail if stale)
    docs_sync.py check --staged              staged files need a valid fragment
    docs_sync.py check --range BASE...HEAD   same for a commit range (CI)
"""
import argparse
import datetime
import re
import subprocess
import sys
from pathlib import Path

FRAGMENT_DIR = "docs/changes"
FRAGMENT_RE = re.compile(r"^docs/changes/\d{4}-\d{2}-\d{2}-[A-Za-z0-9._-]+\.md$")
EXEMPT_PREFIXES = ("docs/",)
EXEMPT_SUFFIXES = (".md",)
EXEMPT_NAMES = {".gitignore", ".gitattributes"}
# file -> (marker name, number of entries shown)
# README shows the 10 newest changes; AGENTS.md lists every change (None = no limit), as the project owner asked.
TARGETS = {"README.md": ("RECENT-CHANGES", 10), "AGENTS.md": ("CHANGE-INDEX", None)}
MIN_FRAGMENT_CHARS = 120
REMAINING_WORK = "docs/REMAINING_WORK.md"
TEMPLATE = """# <one-line title: what changed>

What changed and why (the cause, not just the symptom).

Verified: <exact commands or runtime checks and their real results>

Open: <what is still untested, unfinished, or known to be wrong>

Docs: <which status docs you updated in this same change (docs/REMAINING_WORK.md and the AGENTS.md narrative), or "no status change: <why>">
"""


def root_dir():
    return Path(__file__).resolve().parent.parent


def is_exempt(path):
    return path in EXEMPT_NAMES or path.startswith(EXEMPT_PREFIXES) or path.endswith(EXEMPT_SUFFIXES)


def fragments(root):
    folder = Path(root) / FRAGMENT_DIR
    if not folder.is_dir():
        return []
    names = sorted((p.name for p in folder.glob("*.md") if FRAGMENT_RE.match(f"{FRAGMENT_DIR}/{p.name}")), reverse=True)
    return [folder / name for name in names]


def fragment_title(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem


def render_block(root, limit):
    entries = fragments(root)
    lines = [f"- {p.name[:10]} — [{fragment_title(p)}]({FRAGMENT_DIR}/{p.name})" for p in entries[:limit]]
    if not lines:
        lines = ["- No change files yet."]
    footer = f"_{len(entries)} change file(s) in [{FRAGMENT_DIR}/]({FRAGMENT_DIR}/); this list is generated by `scripts/docs_sync.py`._"
    return "\n".join(lines + ["", footer])


def replace_block(text, name, body):
    start, end = f"<!-- {name}:START -->", f"<!-- {name}:END -->"
    s, e = text.find(start), text.find(end)
    if s == -1 or e == -1 or e < s:
        raise ValueError(f"markers {start} / {end} not found")
    return text[: s + len(start)] + "\n" + body + "\n" + text[e:]


def generate(root, verify=False):
    """Rewrite the generated blocks. Returns the list of files that changed (or would change)."""
    changed = []
    for name, (marker, limit) in TARGETS.items():
        path = Path(root) / name
        # Preserve legacy non-UTF-8 bytes while comparing generated blocks; some historical
        # README content contains extended-ASCII punctuation and must not be rewritten.
        with open(path, encoding="utf-8", errors="surrogateescape", newline="") as handle:
            raw = handle.read()  # newline="" keeps CRLF intact so line endings are never rewritten
        newline = "\r\n" if "\r\n" in raw else "\n"
        updated = replace_block(raw.replace("\r\n", "\n"), marker, render_block(root, limit))
        if updated.replace("\n", newline) != raw:
            changed.append(name)
            if not verify:
                with open(path, "w", encoding="utf-8", errors="surrogateescape", newline="") as handle:
                    handle.write(updated.replace("\n", newline))
    return changed


def missing_from_index(root):
    """Change files that AGENTS.md does not link. Reads the directory and the file directly, not through render_block,
    so a limit or bug in the generator cannot hide a gap (it once cut the index to the newest 15)."""
    agents = Path(root) / "AGENTS.md"
    if not agents.is_file():
        return []
    text = agents.read_text(encoding="utf-8")
    start, end = text.find("<!-- CHANGE-INDEX:START -->"), text.find("<!-- CHANGE-INDEX:END -->")
    block = text[start:end] if start != -1 and end > start else text
    folder = Path(root) / FRAGMENT_DIR
    names = sorted(p.name for p in folder.glob("*.md") if FRAGMENT_RE.match(f"{FRAGMENT_DIR}/{p.name}")) if folder.is_dir() else []
    return [name for name in names if f"{FRAGMENT_DIR}/{name}" not in block]


def validate_fragment(text):
    problems = []
    first = next((line for line in text.splitlines() if line.strip()), "")
    if not first.startswith("# ") or len(first.strip()) < 6:
        problems.append("first line must be a '# Title'")
    if len(text.strip()) < MIN_FRAGMENT_CHARS:
        problems.append(f"too short (< {MIN_FRAGMENT_CHARS} characters)")
    lowered = text.lower()
    for word in ("verified", "open"):
        if word not in lowered:
            problems.append(f"missing a '{word.capitalize()}:' line")
    if "<one-line title" in text or "<exact commands" in text or "<what is still" in text or "<which status docs" in text:
        problems.append("template placeholders were not filled in")
    if docs_line(text) is None:
        problems.append("missing a 'Docs:' line (say which status docs you updated, or 'no status change: <why>')")
    return problems


def docs_line(text):
    """The text after 'Docs:' at the start of a line, or None when there is no such line or it is empty."""
    match = re.search(r"^Docs:[ 	]*(.+)$", text, re.MULTILINE)
    return match.group(1).strip() if match and match.group(1).strip() else None


def claims_no_status_change(text):
    value = (docs_line(text) or "").lower()
    return value.startswith("no status change") and len(value) >= len("no status change: x") + 8  # a real reason, not just the phrase


def check_files(changed, root):
    """Return a list of problems for a set of changed paths."""
    needs = [f for f in changed if not is_exempt(f)]
    if not needs:
        return []
    shown = ", ".join(needs[:5]) + (f" (+{len(needs) - 5} more)" if len(needs) > 5 else "")
    frags = [f for f in changed if FRAGMENT_RE.match(f)]
    if not frags:
        return [f"{len(needs)} non-doc file(s) changed ({shown}) but no new docs/changes/ file. Run: python scripts/docs_sync.py new <slug>"]
    problems = []
    for frag in frags:
        path = Path(root) / frag
        if path.exists():
            text = path.read_text(encoding="utf-8")
            problems += [f"{frag}: {p}" for p in validate_fragment(text)]
            # A change that says it updated the status docs must actually include the remaining-work file.
            if docs_line(text) and not claims_no_status_change(text) and REMAINING_WORK not in changed:
                problems.append(f"{frag}: its Docs: line says status docs were updated, but {REMAINING_WORK} is not part of this change "
                                f"(update it, or write 'Docs: no status change: <reason>')")
    return problems


def git_lines(root, *args):
    result = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or "git failed")
    return [line for line in result.stdout.splitlines() if line]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    new = sub.add_parser("new")
    new.add_argument("slug")
    gen = sub.add_parser("generate")
    gen.add_argument("--verify", action="store_true")
    chk = sub.add_parser("check")
    group = chk.add_mutually_exclusive_group(required=True)
    group.add_argument("--staged", action="store_true")
    group.add_argument("--range")
    args = parser.parse_args(argv)
    root = root_dir()

    if args.cmd == "new":
        slug = re.sub(r"[^A-Za-z0-9._-]+", "-", args.slug).strip("-").lower()
        if not slug:
            print("slug must contain letters or digits", file=sys.stderr)
            return 2
        now = datetime.datetime.now()
        path = root / FRAGMENT_DIR / f"{now.date().isoformat()}-{now.strftime('%H%M')}-{slug}.md"
        if path.exists():
            print(f"{path.relative_to(root)} already exists", file=sys.stderr)
            return 2
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(TEMPLATE, encoding="utf-8")
        print(path.relative_to(root).as_posix())
        return 0

    if args.cmd == "generate":
        changed = generate(root, verify=args.verify)
        if args.verify and changed:
            print("stale generated blocks: " + ", ".join(changed) + ". Run: python scripts/docs_sync.py generate", file=sys.stderr)
            return 1
        if args.verify:
            missing = missing_from_index(root)
            if missing:
                shown = ", ".join(missing[:5]) + (f" (+{len(missing) - 5} more)" if len(missing) > 5 else "")
                print(f"AGENTS.md does not list {len(missing)} change file(s): {shown}", file=sys.stderr)
                return 1
        # Bare LF on every platform: a hook captures this with $(...) and a stray CR would make `git add` fail.
        # .buffer: text mode would turn "\n" into "\r\n" on Windows
        sys.stdout.buffer.write("".join(f"{name}\n" for name in changed).encode("utf-8"))
        sys.stdout.flush()
        return 0

    try:
        if args.staged:
            changed = git_lines(root, "diff", "--cached", "--name-only", "--diff-filter=ACMR")
        else:
            changed = git_lines(root, "diff", "--name-only", "--diff-filter=ACMR", args.range)
    except RuntimeError as error:
        print(f"cannot list changed files: {error}", file=sys.stderr)
        return 2
    problems = check_files(changed, root)
    for problem in problems:
        print(f"docs-sync: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
